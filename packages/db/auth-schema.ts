export const usageEvent = pgTable(
  "usage_event",
  {
    id: text("id").primaryKey(),
    organizationId: text("organization_id")
      .notNull()
      .references(() => organization.id, { onDelete: "cascade" }),
    workerId: text("worker_id")
      .notNull()
      .references(() => worker.id, { onDelete: "cascade" }),
    keyId: text("key_id").references(() => apikey.id, { onDelete: "set null" }),
    model: text("model").notNull(),
    task: text("task").notNull(),
    promptTokens: integer("prompt_tokens").default(0).notNull(),
    completionTokens: integer("completion_tokens").default(0).notNull(),
    finishReason: text("finish_reason"),
    durationMs: integer("duration_ms"),
    createdAt: timestamp("created_at", { mode: "date", precision: 3 })
      .defaultNow()
      .notNull(),
  },
  (table) => [
    index("usageEvent_organizationId_createdAt_idx").on(
      table.organizationId,
      table.createdAt,
    ),
    index("usageEvent_keyId_createdAt_idx").on(table.keyId, table.createdAt),
    index("usageEvent_workerId_createdAt_idx").on(table.workerId, table.createdAt),
  ],
);
